// Typed words are accepted from the curated list PLUS the pre-Phase-2 banks.
// The old model could emit a word the 4,096 list dropped ("harbourside" was
// PLACES[30]), and those holders must still be able to type what they were
// given. Accepting them here cannot move an index in WORDS: derivation hashes
// the words as typed, and phraseFromHash still indexes the curated list.
const WORD_SET = new Set([
	...WORDS,
	...ADJECTIVES.map((word) => word.toLowerCase()),
	...ANIMALS.map((word) => word.toLowerCase()),
	...VERBS.map((word) => word.toLowerCase()),
	...PLACES.map((word) => word.toLowerCase()),
]);

// The word banks double as the display-name vocabulary and legacy passkey fallback.
export { ADJECTIVES, ANIMALS, PLACES, VERBS };
export { ANIMALS as NOUNS };

/**
 * Deterministic 64-hex hash for any string (passkeys and sync rooms).
 */
export function deriveHexHash(input) {
  const normalized = String(input || "")
    .trim()
    .toLowerCase();
  if (/^[0-9a-f]{64}$/.test(normalized)) {
    return normalized;
  }
  let hex = "";
  for (let chunk = 0; chunk < 8; chunk++) {
    let h = (0x811c9dc5 ^ Math.imul(chunk + 1, 0x9e3779b1)) >>> 0;
    for (let i = 0; i < normalized.length; i++) {
      h ^= normalized.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
    h ^= h >>> 16;
    h = Math.imul(h, 0x85ebca6b) >>> 0;
    h ^= h >>> 13;
    h = Math.imul(h, 0xc2b2ae35) >>> 0;
    h ^= h >>> 16;
    hex += (h >>> 0).toString(16).padStart(8, "0");
  }
  return hex;
}

function normalizeHash(vaultHash) {
  const hash = typeof vaultHash === "string" ? vaultHash.trim() : "";
  return {
    hash: hash || FALLBACK_HASH,
    isFallback: !hash,
  };
}

function hashToIndex(hash, array, offset = 0) {
  const segment = hash.slice(offset, offset + 8) || hash;
  return Number.parseInt(segment, 16) % array.length;
}

function pickWord(bank = WORDS) {
  const max = Math.floor(0xffffffff / bank.length) * bank.length;
  const buf = new Uint32Array(1);
  let value;
  do {
    globalThis.crypto.getRandomValues(buf);
    value = buf[0];
  } while (value >= max);
  return bank[value % bank.length];
}

/**
 * Forgiving normalizer: case, spaces, underscores, and stray punctuation all
 * normalize to hyphenated lowercase words.
 */
export function normalizePassphrase(value) {
  return String(value ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .join("-");
}

export const normalizeSyncPhrase = normalizePassphrase;
export const normalizePasskeyPhrase = normalizePassphrase;

export function isValidSyncPhrase(value, minWords = 2) {
  const words = normalizePassphrase(value).split("-").filter(Boolean);
  return words.length >= minWords;
}

/**
 * Generate a cryptographically random 4-word passphrase from the 4,096-word bank (48 bits).
 */
export function generatePassphrase() {
  return [
    pickWord(WORDS),
    pickWord(WORDS),
    pickWord(WORDS),
    pickWord(WORDS),
  ].join("-");
}

export const generateSyncPhrase = generatePassphrase;

/**
 * Deterministically maps a 64-hex digest (e.g. HMAC(secret, phraseInput(seed)))
 * to 4 words from the 4,096-word bank. 4096 = 2^12 divides 2^32 evenly, so
 * 8-hex-char chunks have zero modulo bias.
 */
export function phraseFromHash(hexHash) {
  const { hash } = normalizeHash(hexHash);
  return [
    WORDS[hashToIndex(hash, WORDS, 0)],
    WORDS[hashToIndex(hash, WORDS, 8)],
    WORDS[hashToIndex(hash, WORDS, 16)],
    WORDS[hashToIndex(hash, WORDS, 24)],
  ].join("-");
}

/**
 * Computes the pre-Phase-2 23.3-bit phrase from a code's vaultHash so
 * existing holders migrating to Passphrase-Root keep their legacySecret
 * during the one-release migration window.
 */
export function deriveLegacyPhrase(hexHash) {
  const { hash } = normalizeHash(hexHash);
  const adj = ADJECTIVES[hashToIndex(hash, ADJECTIVES, 0)].toLowerCase();
  const animal = ANIMALS[hashToIndex(hash, ANIMALS, 8)].toLowerCase();
  const verb = VERBS[hashToIndex(hash, VERBS, 32)].toLowerCase();
  const place = PLACES[hashToIndex(hash, PLACES, 40)].toLowerCase();
  return `${adj}-${animal}-${verb}-${place}`;
}

/**
 * Masks the 4-word passphrase on the resting card face so screenshots never
 * leak a bearer credential.
 */
export function maskPassphrase(phrase) {
  const normalized = normalizePassphrase(phrase);
  if (!normalized) return "••••• ••••• ••••• •••••";
  const count = Math.max(4, normalized.split("-").filter(Boolean).length);
  return Array.from({ length: count }, () => "•••••").join(" ");
}

/**
 * Parses and validates a 4-word passphrase against the 4,096-word curated bank
 * (which is a superset of all legacy ADJECTIVES/ANIMALS/VERBS/PLACES words).
 * Fails cleanly in < 1ms if any word is not in the bank, without revealing which word failed.
 */
export function parseFourWordPasskey(input) {
  if (typeof input !== "string") return null;
  const trimmed = input.trim();
  if (!trimmed) return null;

  const parts = trimmed
    .toLowerCase()
    .split(/[\s_-]+/)
    .filter(Boolean);
  if (parts.length !== PASSPHRASE_WORD_COUNT) return null;
  if (!parts.every((word) => WORD_SET.has(word))) return null;

  const phrase = parts.join("-");
  const matchedAdj = ADJECTIVES.find((item) => item.toLowerCase() === parts[0]);
  const matchedAnimal = ANIMALS.find((item) => item.toLowerCase() === parts[1]);
  const fallbackHash = deriveHexHash(phrase);
  const adj = matchedAdj || ADJECTIVES[hashToIndex(fallbackHash, ADJECTIVES, 0)];
  const animal = matchedAnimal || ANIMALS[hashToIndex(fallbackHash, ANIMALS, 8)];

  return {
    adj,
    animal,
    verb: parts[2],
    place: parts[3],
    name: `${adj} ${animal}`,
    phrase,
    initials: `${adj[0]}${animal[0]}`,
    words: parts,
  };
}

export const parsePassphrase = parseFourWordPasskey;

export function isValidPassphrase(input) {
  return parseFourWordPasskey(input) !== null;
}

export function getSyncRoomId(input) {
  if (typeof input !== "string") return "";
  const trimmed = input.trim();
  if (!trimmed) return "";

  const parsed = parseFourWordPasskey(trimmed);
  const canonical = parsed ? parsed.phrase : normalizePassphrase(trimmed) || trimmed.toLowerCase();
  return deriveHexHash(canonical);
}

export function generateMemberIdentity(vaultHash, code, options = {}) {
  const explicitPhrase =
    typeof options === "string"
      ? normalizePassphrase(options)
      : typeof options?.phrase === "string"
        ? normalizePassphrase(options.phrase)
        : "";
  const explicitName =
    typeof options === "object" && options !== null && typeof options.name === "string"
      ? options.name.trim()
      : "";

  const parsedPasskey =
    parseFourWordPasskey(code) || parseFourWordPasskey(vaultHash);
  if (parsedPasskey) {
    const canonicalHash = getSyncRoomId(parsedPasskey.phrase);
    const bg = BG_COLORS[hashToIndex(canonicalHash, BG_COLORS, 16)];
    const shape = SHAPE_COLORS[hashToIndex(canonicalHash, SHAPE_COLORS, 24)];
    const isSS = /^SS-[A-F0-9]{4}-[A-F0-9]{4}-[A-F0-9]{4}$/i.test(
      String(code ?? "").trim(),
    );
    const memberId = isSS
      ? String(code).trim().toUpperCase()
      : `SS-${canonicalHash.slice(0, 4).toUpperCase()}-${canonicalHash.slice(4, 8).toUpperCase()}-${canonicalHash.slice(8, 12).toUpperCase()}`;
    const name = explicitName || parsedPasskey.name;
    const initials =
      name
        .split(/\s+/)
        .filter(Boolean)
        .slice(0, 2)
        .map((w) => w[0].toUpperCase())
        .join("") || parsedPasskey.initials;

    return {
      name,
      phrase: explicitPhrase || parsedPasskey.phrase,
      memberId,
      initials,
      bg,
      shape,
      syncRoomId: canonicalHash,
      isFallback: false,
    };
  }

  const { hash, isFallback } = normalizeHash(vaultHash);
  if (isFallback) {
    return {
      name: "Passport Pending",
      memberId: code || "SS-PENDING",
      initials: "SS",
      bg: "fff1f2",
      shape: "f9a8d4",
      isFallback: true,
    };
  }

  const adj = ADJECTIVES[hashToIndex(hash, ADJECTIVES, 0)];
  const animal = ANIMALS[hashToIndex(hash, ANIMALS, 8)];
  const bg = BG_COLORS[hashToIndex(hash, BG_COLORS, 16)];
  const shape = SHAPE_COLORS[hashToIndex(hash, SHAPE_COLORS, 24)];
  const memberId =
    code ||
    `SS-${hash.slice(0, 4).toUpperCase()}-${hash.slice(4, 8).toUpperCase()}-${hash.slice(8, 12).toUpperCase()}`;
  const name = explicitName || `${adj} ${animal}`;
  const initials =
    name
      .split(/\s+/)
      .filter(Boolean)
      .slice(0, 2)
      .map((w) => w[0].toUpperCase())
      .join("") || `${adj[0]}${animal[0]}`;
  // No phrase in the bank was supplied, so there is no passkey to show. The
  // hash-derived words this used to invent (`phraseFromHash(hash)`) unlock
  // nothing: the card's copy chip copied them, the emailed card printed them,
  // and ZipList built a pairing QR out of them. Show only what a caller
  // actually provided; everything downstream already falls back to the code.
  const phrase = explicitPhrase;
  const legacyPhrase = deriveLegacyPhrase(hash);

  return {
    name,
    phrase,
    legacyPhrase,
    memberId,
    initials,
    bg,
    shape,
    syncRoomId: getSyncRoomId(phrase),
    isFallback: false,
  };
}
